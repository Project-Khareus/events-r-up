// Live countries first, then the rest alphabetically.
export const COUNTRY_OPTIONS = [
  ...AFRICAN_COUNTRIES.filter((c) => LIVE_COUNTRY_CODES.includes(c.code)),
  ...AFRICAN_COUNTRIES.filter((c) => !LIVE_COUNTRY_CODES.includes(c.code)),
];

export function countryFlag(code) {
  if (!code || code.length !== 2) return "";
  return String.fromCodePoint(...[...code.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}

export function getCountryName(code) {
  return AFRICAN_COUNTRIES.find((c) => c.code === code)?.name || code || "";
}

// Records saved before the country field existed are Ghanaian.
export function isLiveCountry(code) {
  return LIVE_COUNTRY_CODES.includes(code || DEFAULT_COUNTRY_CODE);
}
